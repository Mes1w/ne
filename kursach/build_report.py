def cell_set(c, t, bold=False, size=12, math=None):
    p = c.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.space_after = Pt(0)
    if math: p._p.append(parse_xml('<m:oMath %s>%s</m:oMath>' % (MNS, math))); return
    r = p.add_run(str(t)); r.font.size = Pt(size); r.bold = bold
def table(rows, widths=None, header=1, size=12, merges=()):
    t = doc.add_table(rows=len(rows), cols=len(rows[0])); t.style = 'Table Grid'; t.alignment = WD_TABLE_ALIGNMENT.CENTER
    if widths:
        t.autofit = False
        for i in range(len(rows)):
            for j, w in enumerate(widths): t.cell(i, j).width = Cm(w)
    covered = set()
    for (r0, c0), (r1, c1) in merges:        # объединяем пустые ячейки, затем заполняем
        t.cell(r0, c0).merge(t.cell(r1, c1))
        covered |= {(i, j) for i in range(r0, r1 + 1) for j in range(c0, c1 + 1)} - {(r0, c0)}
    for i, row in enumerate(rows):
        for j, v in enumerate(row):
            if (i, j) in covered: continue
            c = t.cell(i, j)
            if isinstance(v, M): cell_set(c, '', math=v.x)
            else: cell_set(c, v, bold=i < header, size=size)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t
