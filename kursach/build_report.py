MNS = 'xmlns:m="http://schemas.openxmlformats.org/officeDocument/2006/math"'
def mr(t): return '<m:r><m:t xml:space="preserve">%s</m:t></m:r>' % t
def msub(b, s): return '<m:sSub><m:e>%s</m:e><m:sub>%s</m:sub></m:sSub>' % (b, mr(s))
def mbar(x): return '<m:bar><m:barPr><m:pos m:val="top"/></m:barPr><m:e>%s</m:e></m:bar>' % x
def mname(n):
    inv = n.startswith('!'); b = n.lstrip('!')
    x = msub(mr(b[0]), b[1:]) if len(b) > 1 else mr(b)
    return mbar(x) if inv else x
def msop(terms):
    if not terms: return mr('0')
    if terms == [(0, 0)]: return mr('1')
    return mr(' + ').join(mr('·').join(mname(l) for l in term_lits(t)) for t in terms)
def mtree(t):
    if t['k'] == 'lit': return mname(t['n'])
    if t['k'] == 'c': return mr(str(t['v']))
    return mbar(mr('·').join(mtree(c) for c in t['ch']))
def mfunc(name, terms, off=0, tree=True):
    """имя = МДНФ [= форма в базисе И-НЕ]"""
    s = mname(name) + mr(' = ') + msop(terms)
    t = sop_to_nand(terms)
    if tree and t['k'] == 'nand': s += mr(' = ') + mtree(t)
    return s
