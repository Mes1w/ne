def para(*parts, align='j', indent=True, bold=False, size=None, after=0, before=0, keep=False, hl=False):
    p = doc.add_paragraph(); f = p.paragraph_format
    f.line_spacing = 1.5; f.space_after = Pt(after); f.space_before = Pt(before)
    f.first_line_indent = Cm(1.25) if indent else Cm(0); f.keep_with_next = keep
    p.alignment = {'j': WD_ALIGN_PARAGRAPH.JUSTIFY, 'c': WD_ALIGN_PARAGRAPH.CENTER, 'l': WD_ALIGN_PARAGRAPH.LEFT, 'r': WD_ALIGN_PARAGRAPH.RIGHT}[align]
    for x in parts:
        if isinstance(x, M): p._p.append(parse_xml('<m:oMath %s>%s</m:oMath>' % (MNS, x.x)))
        else:
            r = p.add_run(x); r.bold = bold
            if size: r.font.size = Pt(size)
            if hl: r.font.highlight_color = WD_COLOR_INDEX.YELLOW
    return p
